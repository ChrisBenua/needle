#!/usr/bin/env python3
"""Generates the shared-protocols benchmark sources.

Writes three things:

  Sources/BenchModels/Generated/Protocols/   N public protocols, `per_file` per file
  Sources/BenchModels/Generated/Classes/     N public final classes, one per protocol
  Sources/BenchNeedle/Generated/             BenchComponent + extensions declaring one
                                             `shared` property per protocol, and the
                                             chunked `accessAll(_:)` driver

Every property uses a two-statement closure:

    public var dep0: Protocol0 {
        shared {
            let instance = Class0()
            return instance
        }
    }

That shape is load-bearing. With a single-expression closure, `shared { Class0() }`,
the type checker binds `shared`'s `T` to `Class0` and the cached-instance cast is a
cheap concrete-class cast. With two statements, `T` is taken from the property's
type, `Protocol0`, and `shared` has to cast its stored `Any` back to a protocol —
which is the slow path this benchmark exists to measure.

Re-running with the same arguments reproduces the committed tree exactly.

    python3 Tools/generate-bench-sources.py                  # 10 000 types
    python3 Tools/generate-bench-sources.py --types 50000
"""

import argparse
import os
import shutil

HEADER = """// AUTO-GENERATED — do not edit by hand.
// Generated by Tools/generate-bench-sources.py

import Foundation
"""


def protocol_file(start, count):
    out = [HEADER]
    for i in range(start, start + count):
        out.append(
            f"""
public protocol Protocol{i} {{
    func identifier() -> String
}}
"""
        )
    return "".join(out)


def class_file(start, count):
    out = [HEADER]
    for i in range(start, start + count):
        out.append(
            f"""
public final class Class{i}: Protocol{i}, Codable {{
    public let id: Int
    public let name: String
    public let value: Double
    public let isActive: Bool
    public let createdAt: Date

    public init(
        id: Int = {i},
        name: String = "Class{i}",
        value: Double = {i}.0,
        isActive: Bool = true,
        createdAt: Date = Date()
    ) {{
        self.id        = id
        self.name      = name
        self.value     = value
        self.isActive  = isActive
        self.createdAt = createdAt
    }}

    // MARK: Protocol{i}
    public func identifier() -> String {{ "Class{i}(\\(id))" }}
}}
"""
        )
    return "".join(out)


def component_file(types):
    return "".join(
        [
            HEADER,
            "\nimport NeedleFoundation\n",
            "\n/// How many protocol/class pairs this benchmark was generated with.\n",
            f"public let benchTypeCount = {types}\n",
            "\n/// The component under test. Its `shared` properties are declared in the\n",
            "/// `BenchComponent_NNNN.swift` extensions.\n",
            "public final class BenchComponent: BootstrapComponent {}\n",
        ]
    )


def extension_file(start, count):
    out = [HEADER, "\nimport BenchModels\nimport NeedleFoundation\n", "\nextension BenchComponent {\n"]
    for i in range(start, start + count):
        out.append(
            f"""
    public var dep{i}: Protocol{i} {{
        shared {{
            let instance = Class{i}()
            return instance
        }}
    }}
"""
        )
    out.append("}\n")
    return "".join(out)


def access_file(types, chunk):
    chunks = list(range(0, types, chunk))
    out = [
        HEADER,
        "\nimport BenchModels\n",
        "\n// MARK: - Public entry point\n\n",
        "/// Reads every `shared` property once, returning the instances so the\n",
        "/// optimiser cannot discard the work.\n",
        "@inline(never)\npublic func accessAll(_ component: BenchComponent) -> [Any] {\n",
        "    var result: [Any] = []\n",
        f"    result.reserveCapacity({types})\n",
    ]
    for n, _ in enumerate(chunks):
        out.append(f"    _access_{n:04d}(component, into: &result)\n")
    out.append("    return result\n}\n")

    # One 10 000-line function does not type-check in reasonable time.
    for n, start in enumerate(chunks):
        out.append(
            f"\n// MARK: chunk {n}\n@inline(never)\n"
            f"private func _access_{n:04d}(_ c: BenchComponent, into out: inout [Any]) {{\n"
        )
        for i in range(start, min(start + chunk, types)):
            out.append(f"    out.append(c.dep{i})\n")
        out.append("}\n")
    return "".join(out)


def rewrite_dir(path, files):
    """Replaces `path` wholesale so a smaller --types leaves no stale files behind."""
    if os.path.isdir(path):
        shutil.rmtree(path)
    os.makedirs(path)
    for name, body in files:
        with open(os.path.join(path, name), "w", encoding="utf-8") as handle:
            handle.write(body)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--types", type=int, default=10000, help="number of protocol/class pairs")
    parser.add_argument("--per-file", type=int, default=10, help="declarations per generated model file")
    parser.add_argument("--chunk", type=int, default=500, help="shared properties per extension / access function")
    parser.add_argument(
        "--out",
        default=os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
        help="benchmark package root (default: the package this script lives in)",
    )
    args = parser.parse_args()

    models = os.path.join(args.out, "Sources", "BenchModels", "Generated")
    starts = list(range(0, args.types, args.per_file))
    chunks = list(range(0, args.types, args.chunk))

    rewrite_dir(
        os.path.join(models, "Protocols"),
        [
            (f"Protocols_{n:04d}.swift", protocol_file(start, min(args.per_file, args.types - start)))
            for n, start in enumerate(starts)
        ],
    )
    rewrite_dir(
        os.path.join(models, "Classes"),
        [
            (f"Classes_{n:04d}.swift", class_file(start, min(args.per_file, args.types - start)))
            for n, start in enumerate(starts)
        ],
    )
    rewrite_dir(
        os.path.join(args.out, "Sources", "BenchNeedle", "Generated"),
        [("BenchComponent.swift", component_file(args.types)), ("Access.swift", access_file(args.types, args.chunk))]
        + [
            (f"BenchComponent_{n:04d}.swift", extension_file(start, min(args.chunk, args.types - start)))
            for n, start in enumerate(chunks)
        ],
    )

    print(
        f"generated {args.types} protocol/class pairs "
        f"({len(starts)} model files each), {len(chunks)} component chunks"
    )


if __name__ == "__main__":
    main()
